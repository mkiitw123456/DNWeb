export function journeyEvents() {
  let secret = 0;
  return scenes.map((line, i) => {
    const [title, story, left, leftResult, right, rightResult] =
      line.split("|");
    const options = [
      [left, leftResult],
      [right, rightResult],
    ].map(([text, result]) => ({
      text,
      outcomes: [{ result, chance: 100, stars: i === 0 ? 5 : 3 }],
    }));
    if ([1, 4].includes(i % 5)) {
      const [text, win, loss] = secrets[secret].split("|");
      const chance = secret % 2 ? 20 : 30;
      options.push({
        text,
        revealChance: 30,
        outcomes: [
          { result: win, chance, stars: chance === 20 ? 12 : 9 },
          { result: loss, chance: 100 - chance, stars: -((secret % 3) + 1) },
        ],
      });
      secret++;
    }
    return {
      id: `journey-${i + 1}`,
      title: `第 ${i + 1} 話 · ${title}`,
      story,
      options,
    };
  });
}
