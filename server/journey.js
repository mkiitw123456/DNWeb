function regularChoice(text, profile, success, setback) {
  const { chance, high, low } = profiles[profile];
  return {
    text,
    outcomes: [
      { result: success, chance, stars: high },
      { result: setback, chance: 100 - chance, stars: low },
    ],
  };
}

export function journeyEvents() {
  let secret = 0;
  return scenes.map((line, i) => {
    const [
      title,
      story,
      left,
      leftProfile,
      leftHigh,
      leftLow,
      right,
      rightProfile,
      rightHigh,
      rightLow,
    ] = line.split("|");
    const options = [
      regularChoice(left, leftProfile, leftHigh, leftLow),
      regularChoice(right, rightProfile, rightHigh, rightLow),
    ];
    if ([1, 4].includes(i % 5)) {
      const [text, win, loss] = secrets[secret].split("|");
      const chance = secret % 2 ? 20 : 30;
      options.push({
        text,
        revealChance: 30,
        outcomes: [
          { result: win, chance, stars: chance === 20 ? 12 : 9 },
          { result: loss, chance: 100 - chance, stars: -((secret % 3) + 1) },
        ],
      });
      secret++;
    }
    return {
      id: `journey-${i + 1}`,
      title: `第 ${i + 1} 話 · ${title}`,
      story,
      options,
    };
  });
}
