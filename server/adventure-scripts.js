// Each chapter pairs two actions with their own success and setback text.
// The optional last three fields describe an independent bonus encounter.
function script(id, title, description, chapters) {
  const rows = chapters.trim().split("\n");
  return {
    id,
    title,
    description,
    events: rows.map((row, i) => {
      const [name, story, a, goodA, mixedA, b, goodB, badB, extra, win, loss] =
        row.split("|");
      const steady = [50, 65, 75][i % 3];
      const risk = [30, 45, 35][i % 3];
      const options = [
        {
          text: a,
          outcomes: [
            { result: goodA, chance: steady, stars: 3 },
            { result: mixedA, chance: 100 - steady, stars: 1 },
          ],
        },
        {
          text: b,
          outcomes: [
            { result: goodB, chance: risk, stars: 5 },
            { result: badB, chance: 100 - risk, stars: -1 },
          ],
        },
      ];
      if (extra)
        options.push({
          text: extra,
          revealChance: 30,
          outcomes: [
            { result: win, chance: i % 2 ? 20 : 30, stars: i % 2 ? 12 : 9 },
            { result: loss, chance: i % 2 ? 80 : 70, stars: i % 2 ? -2 : -3 },
          ],
        });
      return {
        id: id + "-" + (i + 1),
        title: `第 ${i + 1} 話 · ${name}`,
        story,
        options,
      };
    }),
  };
}

